let currentLang = 'en';

function t(key) {
  const parts = key.split('.');
  let value = translations[currentLang];
  for (const part of parts) {
    value = value?.[part];
  }
  if (value === undefined && currentLang !== 'en') {
    value = translations.en;
    for (const part of parts) {
      value = value?.[part];
    }
  }
  return value ?? '';
}

function detectLanguage() {
  if (/^\/ru(\/|$)/.test(window.location.pathname)) return 'ru';
  return 'en';
}

function updateLangSwitcher() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isActive = btn.dataset.lang === currentLang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-current', isActive ? 'page' : 'false');
  });
}

function applyTranslations() {
  document.documentElement.lang = currentLang;

  const title = t('meta.title');
  const desc = t('meta.description');
  if (title) document.title = title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', desc);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  updateLangSwitcher();
  document.documentElement.classList.remove('wc-i18n-pending');
  document.documentElement.classList.add('wc-i18n-ready');

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: currentLang } }));
}

function initI18n() {
  currentLang = detectLanguage();

  if (currentLang === 'ru') {
    applyTranslations();
  } else {
    updateLangSwitcher();
    document.documentElement.classList.remove('wc-i18n-pending');
  }
}

window.i18n = { t, getLanguage: () => currentLang };
